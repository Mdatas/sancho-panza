#!/usr/bin/env python3
"""Regenerate data/build_orders/benchmarks.json from the graded benchmark blocks in data/knowledge/builds_pros_referencia.md."""
import json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
t = (ROOT / 'data/knowledge/builds_pros_referencia.md').read_text(encoding='utf8')
out = []
for s in re.split(r'\n(?=## )', t):
    m = re.match(r'## (\d+)\. (.+?)(?: \[CIC\] (\S+))?\n', s)
    if not m: continue
    bm = re.search(r'\*\*Benchmarks[^\n]*\*\*:?\n((?:- .+\n?)+)', s)
    if not bm: continue
    rows = []
    for line in bm.group(1).strip().split('\n'):
        mm = re.match(r'- (.+?): ((?:\d+:\d\d\s*/\s*){5}\d+:\d\d)', line.strip())
        if mm: rows.append({'milestone': mm.group(1).strip(), 'times': dict(zip(['A+', 'A', 'B', 'C', 'D', 'E'], [x.strip() for x in mm.group(2).split('/')]))})
    if rows: out.append({'build': m.group(2).strip(), 'source': m.group(3), 'milestones': rows})
doc = {'_about': "Graded timing benchmarks per build (A+ = pro execution … E = slow), copied from Cicero's Build Order Reference (mirror by Joh, no publication date) as summarised in data/knowledge/builds_pros_referencia.md. Not ELO-specific: compare your own game times against the grades. Generated by tools/benchmarks.py; do not edit by hand.", 'grades': ['A+', 'A', 'B', 'C', 'D', 'E'], 'builds': out}
(ROOT / 'data/build_orders/benchmarks.json').write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding='utf8')
print(len(out), 'builds with benchmarks')
